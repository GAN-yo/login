// 获取当前系统推算的显示年份
function getDisplayYear() {
    var now = new Date();
    var currentYear = now.getFullYear();
    var currentMonth = now.getMonth() + 1; // getMonth() 返回 0-11
    // 如果当前年份小于等于2027，则返回2027（故事起点）
    // 否则根据月份推算学年：7月之前属于上一学年，7月及之后属于新学年
    if (currentYear <= 2027) {
        return 2027;
    } else {
        if (currentMonth < 7) {
            return currentYear - 1;
        } else {
            return currentYear;
        }
    }
}

// 根据年份生成当前学号（规则：年份后两位 + 0512）
function getStudentID() {
    var year = getDisplayYear();
    var yearSuffix = (year % 100).toString().padStart(2, '0');
    return yearSuffix + '0512';
}

// 获取校庆日期（固定为 2011年2月5日）
function getAnniversaryDate() {
    return '2011年2月5日';
}

